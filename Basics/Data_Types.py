# integer
print(8)

# 1*10^308
print(1e309)

# Decimal/Float
print(8.55)
print(1.7e309)

# Boolean
print(True)
print(False)

# Text/String
print("Hello World")

# complex
print(6 + 5j)

# list
print([1, 2, 3, 4, 5])

# Tuple
print((1, 2, 3, 4, 5))

# sets
print({1, 2, 3, 4, 5})

# Dictionary
print({"name": "Nitish", "gender": "Male", "weight": 70})

# type
print(type([1, 2, 3, 4]))
print(type(2))
print(type({"name": "Nitish", "gender": "Male", "weight": 70}))
